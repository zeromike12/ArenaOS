    #[test]
    fn clip_restricts_every_operation_exactly() {
        // Drawing the same scene clipped must equal the unclipped scene
        // inside the clip and leave every pixel outside it untouched.
        fn scene(c: &mut Canvas<'_>) {
            c.clear(0x0011_2233);
            c.fill_rect(
                Rect {
                    x: 3,
                    y: 2,
                    width: 20,
                    height: 9,
                },
                0x00ff_0000,
            );
            let src = [0x00aa_bbccu32; 6 * 4];
            c.blit(&src, 6, 4, 6, 10, 5).unwrap();
            c.text_scaled(1, 8, "Ab9", 0x0000_ff00, 2).unwrap();
        }
        let (w, h) = (32usize, 24usize);
        let mut full = [0u32; 32 * 24];
        scene(&mut Canvas::new(&mut full, w, h, w).unwrap());
        let clip = Rect {
            x: 7,
            y: 4,
            width: 11,
            height: 13,
        };
        let mut part = [0xdead_beefu32; 32 * 24];
        let mut c = Canvas::new(&mut part, w, h, w).unwrap();
        c.set_clip(clip);
        assert_eq!(c.clip(), clip);
        scene(&mut c);
        for y in 0..h {
            for x in 0..w {
                let inside = (7..18).contains(&x) && (4..17).contains(&y);
                let expect = if inside { full[y * w + x] } else { 0xdead_beef };
                assert_eq!(part[y * w + x], expect, "({x},{y})");
            }
        }
        // Clip is intersected with the canvas; reset restores everything.
        let mut c = Canvas::new(&mut part, w, h, w).unwrap();
        c.set_clip(Rect {
            x: -5,
            y: 20,
            width: 100,
            height: 100,
        });
        assert_eq!(
            c.clip(),
            Rect {
                x: 0,
                y: 20,
                width: 32,
                height: 4
            }
        );
        c.set_clip(Rect {
            x: 40,
            y: 40,
            width: 4,
            height: 4,
        });
        assert_eq!(
            c.fill_rect(
                Rect {
                    x: 0,
                    y: 0,
                    width: 32,
                    height: 24
                },
                1
            ),
            0
        );
        c.reset_clip();
        assert_eq!(
            c.fill_rect(
                Rect {
                    x: 0,
                    y: 0,
                    width: 32,
                    height: 24
                },
                1
            ),
            32 * 24
        );
    }
    #[test]
    fn origin_translates_every_operation_exactly() {
        let src = [0x00aa_bbccu32; 4 * 3];
        let mask = [255u8, 128, 0, 64];
        let icon = [0b101u16, 0b010];
        let draw = |c: &mut Canvas<'_>, dx: i32, dy: i32| {
            c.fill_rect(
                Rect {
                    x: 2 + dx,
                    y: 1 + dy,
                    width: 5,
                    height: 4,
                },
                0x0010_2030,
            );
            c.blit(&src, 4, 3, 4, 6 + dx, 7 + dy).unwrap();
            c.text_scaled(1 + dx, 9 + dy, "Ab", 0x0000_ff00, 1).unwrap();
            c.text13(12 + dx, 2 + dy, "Hi, gy", 0x00ff_00ff, true)
                .unwrap();
            c.mask_blit(&mask, 2, 2, 2, 20 + dx, 12 + dy, 0x00ff_ffff)
                .unwrap();
            c.bits_blit(&icon, 3, 24 + dx, 14 + dy, 0x0000_00ff);
            c.blend_rect(
                Rect {
                    x: 3 + dx,
                    y: 3 + dy,
                    width: 10,
                    height: 10,
                },
                0x00ff_ff00,
                100,
            );
        };
        let mut a = [0x0011_1111u32; 40 * 24];
        let mut b = a;
        let mut ca = Canvas::new(&mut a, 40, 24, 40).unwrap();
        ca.set_clip(Rect {
            x: 4,
            y: 2,
            width: 30,
            height: 18,
        });
        draw(&mut ca, 5, 3);
        let mut cb = Canvas::new(&mut b, 40, 24, 40).unwrap();
        cb.set_clip(Rect {
            x: 4,
            y: 2,
            width: 30,
            height: 18,
        });
        cb.set_origin(5, 3);
        draw(&mut cb, 0, 0);
        assert_eq!(a, b);
        // Hostile coordinates with an origin never overflow or escape.
        let mut c = Canvas::new(&mut a, 40, 24, 40).unwrap();
        c.set_origin(i32::MAX, i32::MIN);
        c.text_scaled(i32::MAX, i32::MIN, "A", 1, 3).unwrap();
        c.text13(i32::MAX, i32::MAX, "A", 1, false).unwrap();
        assert_eq!(
            c.fill_rect(
                Rect {
                    x: i32::MAX,
                    y: 0,
                    width: u32::MAX,
                    height: 1
                },
                0
            ),
            0
        );
    }

