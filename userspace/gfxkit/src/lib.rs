//! Phase-9 reusable, standalone no_std bitmap toolkit.
//!
//! All graphics operations use caller-owned slices and checked geometry;
//! neither a framebuffer address nor a kernel/device cap exists here. An
//! 800x600 scanout and a 320x200 client surface share the same routines.
//! `Canvas` cannot index outside its borrowed backing even for malicious
//! rectangles, negative coordinates, overflow-sized dimensions or text.
#![no_std]

pub const MAX_WIDTH: usize = 1024;
pub const MAX_HEIGHT: usize = 768;
pub const MAX_TEXT_BYTES: usize = 96;

/// Arena Sans 13, the proportional face (Phase 11.7). Generated by
/// tools/gen_face13.py; kept byte-for-byte as generated.
#[rustfmt::skip]
pub mod face13;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DrawError {
    InvalidGeometry,
    InvalidText,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Rect {
    pub x: i32,
    pub y: i32,
    pub width: u32,
    pub height: u32,
}

/// Opaque XRGB pixels; `stride` is in 32-bit pixels, not bytes.
/// A canvas borrows the complete span so there can be no alias with a
/// second mutable renderer in the same process.
pub struct Canvas<'a> {
    pixels: &'a mut [u32],
    width: usize,
    height: usize,
    stride: usize,
    /// Half-open pixel clip `[x0, x1) x [y0, y1)`, always inside the canvas.
    /// Every drawing operation is intersected with it; it defaults to the
    /// whole canvas, so callers that never set it see unchanged behaviour.
    clip: (usize, usize, usize, usize),
    /// Translation added to every coordinate a caller passes (scroll views,
    /// nested panels). Zero unless set, so existing callers are unchanged.
    origin: (i32, i32),
}

/// Blend `color` over `dst` with coverage `alpha` (0..=255), per channel.
pub fn blend(dst: u32, color: u32, alpha: u8) -> u32 {
    let a = u32::from(alpha);
    let mut out = 0;
    for shift in [0, 8, 16] {
        let d = (dst >> shift) & 0xff;
        let c = (color >> shift) & 0xff;
        out |= ((c * a + d * (255 - a) + 127) / 255) << shift;
    }
    out
}

/// Inked width of `text` in Arena Sans 13 (1 px between glyphs; bold adds
/// one column per glyph). Unknown characters measure as `?`.
pub fn measure13(text: &str, bold: bool) -> i32 {
    let mut w = 0i32;
    for (i, c) in text.chars().enumerate() {
        let g = face13::glyph(c).or_else(|| face13::glyph('?'));
        let gw = g.map_or(0, |g| i32::from(g.width)) + i32::from(bold);
        w += gw + i32::from(i != 0);
    }
    w
}

impl<'a> Canvas<'a> {
    pub fn new(
        pixels: &'a mut [u32],
        width: usize,
        height: usize,
        stride: usize,
    ) -> Result<Self, DrawError> {
        if width == 0
            || height == 0
            || width > MAX_WIDTH
            || height > MAX_HEIGHT
            || stride < width
            || stride > MAX_WIDTH
            || stride
                .checked_mul(height)
                .is_none_or(|size| size > pixels.len())
        {
            return Err(DrawError::InvalidGeometry);
        }
        Ok(Self {
            pixels,
            width,
            height,
            stride,
            clip: (0, 0, width, height),
            origin: (0, 0),
        })
    }

    /// Translate every later coordinate by (`x`, `y`) (absolute, not
    /// cumulative). The clip is unaffected: it stays in canvas pixels.
    pub fn set_origin(&mut self, x: i32, y: i32) {
        self.origin = (x, y);
    }

    pub fn origin(&self) -> (i32, i32) {
        self.origin
    }

    fn at(&self, x: i32, y: i32) -> (i64, i64) {
        (
            i64::from(x) + i64::from(self.origin.0),
            i64::from(y) + i64::from(self.origin.1),
        )
    }

    /// The part of `rect` (caller coordinates) inside the clip, in canvas
    /// pixels: `(x0, y0, x1, y1)`, possibly empty.
    fn span(&self, rect: Rect) -> (usize, usize, usize, usize) {
        let (cx0, cy0, cx1, cy1) = self.clip;
        let (x, y) = self.at(rect.x, rect.y);
        let x0 = x.clamp(cx0 as i64, cx1 as i64) as usize;
        let y0 = y.clamp(cy0 as i64, cy1 as i64) as usize;
        let x1 = (x + i64::from(rect.width)).clamp(x0 as i64, cx1 as i64) as usize;
        let y1 = (y + i64::from(rect.height)).clamp(y0 as i64, cy1 as i64) as usize;
        (x0, y0, x1, y1)
    }

    /// Blend `color` with coverage `alpha` over the opaque pixels of
    /// `rect` (selection washes, scrims, hover tints). Returns pixels touched.
    pub fn blend_rect(&mut self, rect: Rect, color: u32, alpha: u8) -> usize {
        let (x0, y0, x1, y1) = self.span(rect);
        for y in y0..y1 {
            for p in &mut self.pixels[y * self.stride + x0..y * self.stride + x1] {
                *p = blend(*p, color, alpha);
            }
        }
        (x1 - x0) * (y1 - y0)
    }

    /// Darken `rect` by `amount` (0..=255 toward black): shadows, pressed.
    pub fn darken_rect(&mut self, rect: Rect, amount: u8) -> usize {
        self.blend_rect(rect, 0, amount)
    }

    /// An 8-bit coverage mask (`width` x `height`, row `stride` bytes)
    /// blended in `color` at (`x`, `y`): soft shadows, smooth icons.
    pub fn mask_blit(
        &mut self,
        mask: &[u8],
        width: usize,
        height: usize,
        stride: usize,
        x: i32,
        y: i32,
        color: u32,
    ) -> Result<usize, DrawError> {
        if width == 0
            || height == 0
            || width > MAX_WIDTH
            || height > MAX_HEIGHT
            || stride < width
            || stride
                .checked_mul(height - 1)
                .and_then(|s| s.checked_add(width))
                .is_none_or(|span| span > mask.len())
        {
            return Err(DrawError::InvalidGeometry);
        }
        let (x0, y0, x1, y1) = self.span(Rect {
            x,
            y,
            width: width as u32,
            height: height as u32,
        });
        let (ox, oy) = self.at(x, y);
        let mut touched = 0;
        for dy in y0..y1 {
            let row = (dy as i64 - oy) as usize * stride;
            for dx in x0..x1 {
                let a = mask[row + (dx as i64 - ox) as usize];
                if a != 0 {
                    let p = &mut self.pixels[dy * self.stride + dx];
                    *p = blend(*p, color, a);
                    touched += 1;
                }
            }
        }
        Ok(touched)
    }

    /// A 1-bit mask (bit `i` of `rows[r]` = column `i`, at most 16 wide)
    /// in `color` at (`x`, `y`): icons and glyph rows as whole spans.
    pub fn bits_blit(&mut self, rows: &[u16], width: usize, x: i32, y: i32, color: u32) -> usize {
        let (ox, oy) = self.at(x, y);
        self.bits_at(rows, width, ox, oy, color)
    }

    /// `bits_blit` at absolute canvas coordinates (i64: never overflows).
    fn bits_at(&mut self, rows: &[u16], width: usize, ox: i64, oy: i64, color: u32) -> usize {
        if width == 0 || width > 16 {
            return 0;
        }
        let (cx0, cy0, cx1, cy1) = self.clip;
        let color = color & 0x00ff_ffff;
        let mut touched = 0;
        for (r, bits) in rows.iter().enumerate() {
            let py = oy + r as i64;
            if py < cy0 as i64 || py >= cy1 as i64 || *bits == 0 {
                continue;
            }
            let line = py as usize * self.stride;
            for i in 0..width {
                let px = ox + i as i64;
                if bits >> i & 1 == 1 && px >= cx0 as i64 && px < cx1 as i64 {
                    self.pixels[line + px as usize] = color;
                    touched += 1;
                }
            }
        }
        touched
    }

    /// Text in Arena Sans 13 with its top at `y`; returns the inked width.
    /// Bold double-strikes one column to the right. Characters the face
    /// lacks draw as `?`; overlong input is a typed refusal before any
    /// pixel changes.
    pub fn text13(
        &mut self,
        x: i32,
        y: i32,
        text: &str,
        color: u32,
        bold: bool,
    ) -> Result<i32, DrawError> {
        if text.chars().count() > 4 * MAX_TEXT_BYTES {
            return Err(DrawError::InvalidText);
        }
        // Pen and coordinates in i64: hostile x/y/origin never overflow.
        let (ox, oy) = self.at(x, y);
        let mut pen = 0i64;
        for (i, c) in text.chars().enumerate() {
            if i != 0 {
                pen += 1;
            }
            let Some(g) = face13::glyph(c).or_else(|| face13::glyph('?')) else {
                continue;
            };
            let w = usize::from(g.width);
            // Whole glyphs outside the clip cost nothing.
            let gx = ox + pen;
            if gx < self.clip.2 as i64 && gx + w as i64 + 1 > self.clip.0 as i64 {
                self.bits_at(&g.rows, w, gx, oy, color);
                if bold {
                    self.bits_at(&g.rows, w, gx + 1, oy, color);
                }
            }
            pen += i64::from(g.width) + i64::from(bold);
        }
        Ok(pen as i32)
    }

    /// Restrict all later drawing to `rect` intersected with the canvas.
    /// Damage-driven compositors use this to recompose only changed areas.
    pub fn set_clip(&mut self, rect: Rect) {
        let x0 = i64::from(rect.x).clamp(0, self.width as i64) as usize;
        let y0 = i64::from(rect.y).clamp(0, self.height as i64) as usize;
        let x1 = (i64::from(rect.x) + i64::from(rect.width)).clamp(0, self.width as i64) as usize;
        let y1 = (i64::from(rect.y) + i64::from(rect.height)).clamp(0, self.height as i64) as usize;
        self.clip = (x0, y0, x1.max(x0), y1.max(y0));
    }

    pub fn reset_clip(&mut self) {
        self.clip = (0, 0, self.width, self.height);
    }

    pub fn clip(&self) -> Rect {
        let (x0, y0, x1, y1) = self.clip;
        Rect {
            x: x0 as i32,
            y: y0 as i32,
            width: (x1 - x0) as u32,
            height: (y1 - y0) as u32,
        }
    }

    pub fn size(&self) -> (usize, usize) {
        (self.width, self.height)
    }

    /// Fill the current clip (the whole canvas unless a clip is set).
    pub fn clear(&mut self, color: u32) {
        let (x0, y0, x1, y1) = self.clip;
        let color = color & 0x00ff_ffff;
        for y in y0..y1 {
            self.pixels[y * self.stride + x0..y * self.stride + x1].fill(color);
        }
    }

    /// Rectangles are intersected with the canvas, never rejected merely
    /// for being partly offscreen. i64 math cannot overflow on i32+u32.
    /// Return the number of pixels actually touched for structural tests.
    pub fn fill_rect(&mut self, rect: Rect, color: u32) -> usize {
        let (x0, y0, x1, y1) = self.span(rect);
        let color = color & 0x00ff_ffff;
        for y in y0..y1 {
            self.pixels[y * self.stride + x0..y * self.stride + x1].fill(color);
        }
        (x1 - x0) * (y1 - y0)
    }

    /// This bitmap font is intentionally small and wholly owned here: each
    /// glyph is seven 5-bit rows, width 5, height 7, fixed advance 6. An
    /// unsupported printable glyph renders '?'; non-ASCII or oversized
    /// input is a typed refusal *before* any pixel is changed.
    pub fn text(&mut self, x: i32, y: i32, text: &str, color: u32) -> Result<usize, DrawError> {
        self.text_scaled(x, y, text, color, 1)
    }
    /// Owned bitmap glyphs at bounded integer scale, preserving case.
    /// Invalid scale or text refuses before changing any destination pixel.
    pub fn text_scaled(
        &mut self,
        x: i32,
        y: i32,
        text: &str,
        color: u32,
        scale: u8,
    ) -> Result<usize, DrawError> {
        if !(1..=3).contains(&scale)
            || text.len() > MAX_TEXT_BYTES
            || !text.bytes().all(|c| c.is_ascii_graphic() || c == b' ')
        {
            return Err(DrawError::InvalidText);
        }
        let mut touched = 0usize;
        let color = color & 0x00ff_ffff;
        let (cx0, cy0, cx1, cy1) = (
            self.clip.0 as i64,
            self.clip.1 as i64,
            self.clip.2 as i64,
            self.clip.3 as i64,
        );
        let (x, y) = (
            x.saturating_add(self.origin.0),
            y.saturating_add(self.origin.1),
        );
        for (i, c) in text.bytes().enumerate() {
            let gx = i64::from(x) + (i as i64) * 6 * i64::from(scale);
            // Whole glyph cells outside the clip cost nothing.
            if gx >= cx1 || gx + 5 * i64::from(scale) <= cx0 {
                continue;
            }
            let bitmap = font::glyph(c);
            for (row, bits) in bitmap.iter().enumerate() {
                let py = i64::from(y) + row as i64 * i64::from(scale);
                if py + i64::from(scale) <= cy0 || py >= cy1 {
                    continue;
                }
                for column in 0..5 {
                    let px = gx + column * i64::from(scale);
                    if px + i64::from(scale) <= cx0
                        || px >= cx1
                        || (bits & (1 << (4 - column))) == 0
                    {
                        continue;
                    }
                    for dy in 0..i64::from(scale) {
                        for dx in 0..i64::from(scale) {
                            let (xx, yy) = (px + dx, py + dy);
                            if xx >= cx0 && yy >= cy0 && xx < cx1 && yy < cy1 {
                                self.pixels[yy as usize * self.stride + xx as usize] = color;
                                touched += 1;
                            }
                        }
                    }
                }
            }
        }
        Ok(touched)
    }

    /// Opaque, clipped z-order composition. The source is a *different*
    /// immutable slice and validated width/stride; the compositor decides
    /// who owns it, not this deliberately authority-free helper.
    pub fn blit(
        &mut self,
        source: &[u32],
        src_width: usize,
        src_height: usize,
        src_stride: usize,
        x: i32,
        y: i32,
    ) -> Result<usize, DrawError> {
        if src_width == 0
            || src_height == 0
            || src_width > MAX_WIDTH
            || src_height > MAX_HEIGHT
            || src_stride < src_width
            || src_stride > MAX_WIDTH
            || src_stride
                .checked_mul(src_height)
                .is_none_or(|span| span > source.len())
        {
            return Err(DrawError::InvalidGeometry);
        }
        let (x0, y0, x1, y1) = self.span(Rect {
            x,
            y,
            width: src_width as u32,
            height: src_height as u32,
        });
        let (x, y) = self.at(x, y);
        let sx0 = (x0 as i64 - x) as usize;
        for dy in y0..y1 {
            let sy = (dy as i64 - y) as usize;
            let src = &source[sy * src_stride + sx0..sy * src_stride + sx0 + (x1 - x0)];
            let dst = &mut self.pixels[dy * self.stride + x0..dy * self.stride + x1];
            for (d, s) in dst.iter_mut().zip(src) {
                *d = *s & 0x00ff_ffff;
            }
        }
        Ok((x1 - x0) * (y1 - y0))
    }
}

