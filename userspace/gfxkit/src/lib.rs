    #[test]
    fn face13_is_complete_measured_and_clipped() {
        // Every glyph's ink lies inside its width and cell; the table is
        // sorted (binary search) and covers printable ASCII.
        for w in face13::GLYPHS.windows(2) {
            assert!(w[0].ch < w[1].ch);
        }
        for g in &face13::GLYPHS {
            assert!((1..=16).contains(&g.width));
            assert!(
                g.rows.iter().all(|r| u32::from(*r) < 1 << g.width),
                "{:?}",
                g.ch
            );
            assert_eq!((g.rows[0], g.rows[12]), (0, 0));
        }
        for c in (b' '..=b'~').map(char::from) {
            assert!(face13::glyph(c).is_some(), "{c:?}");
        }
        for c in [
            '\u{2018}', '\u{2019}', '\u{201c}', '\u{201d}', '\u{2013}', '\u{2014}', '\u{2026}',
        ] {
            assert!(face13::glyph(c).is_some());
        }
        // Case distinct; proportional (i narrower than m).
        for c in b'a'..=b'z' {
            let (l, u) = (char::from(c), char::from(c.to_ascii_uppercase()));
            assert_ne!(
                face13::glyph(l).unwrap().rows,
                face13::glyph(u).unwrap().rows
            );
        }
        assert!(measure13("i", false) < measure13("m", false));
        let mut px = [0u32; 120 * 16];
        let mut c = Canvas::new(&mut px, 120, 16, 120).unwrap();
        for (s, bold) in [
            ("Hello, World!", false),
            ("Documents \u{2014} 3 items", true),
            ("\u{263a}x", false),
        ] {
            assert_eq!(c.text13(0, 0, s, 1, bold).unwrap(), measure13(s, bold));
        }
        assert_eq!(measure13("\u{263a}", false), measure13("?", false));
        // Refusal before any pixel changes.
        let before = px;
        let mut c = Canvas::new(&mut px, 120, 16, 120).unwrap();
        let long = [b'x'; 4 * MAX_TEXT_BYTES + 1];
        let long = core::str::from_utf8(&long).unwrap();
        assert_eq!(c.text13(0, 0, long, 1, false), Err(DrawError::InvalidText));
        assert_eq!(px, before);
        // Clipped text equals unclipped text inside the clip, untouched outside.
        let mut full = [0u32; 60 * 16];
        let mut cf = Canvas::new(&mut full, 60, 16, 60).unwrap();
        cf.text13(-3, 1, "Quick fox, jumps", 0x00ff_ffff, false)
            .unwrap();
        let mut part = [0u32; 60 * 16];
        let mut cp = Canvas::new(&mut part, 60, 16, 60).unwrap();
        cp.set_clip(Rect {
            x: 10,
            y: 3,
            width: 30,
            height: 8,
        });
        cp.text13(-3, 1, "Quick fox, jumps", 0x00ff_ffff, false)
            .unwrap();
        for y in 0..16 {
            for x in 0..60 {
                let inside = (10..40).contains(&x) && (3..11).contains(&y);
                let want = if inside { full[y * 60 + x] } else { 0 };
                assert_eq!(part[y * 60 + x], want, "{x},{y}");
            }
        }
    }
