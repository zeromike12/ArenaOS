#![no_std]
#![no_main]

use core::arch::global_asm;
use core::panic::PanicInfo;

// MMX aliases the x87 register bank. Two isolated processes keep different
// patterns live in MM0-MM7 while timer interrupts and SYS_THREAD_YIELD force
// real scheduler switches. The state oracle is the restored MMX contents.
global_asm!(
    ".section .text",
    ".p2align 4",
    ".globl _start",
    "_start:",
    "mov r14d, edi",
    "cmp r14d, 1",
    "jne .Lmmx_worker_b",
    "movabs rbx, 0xA15A000000001000",
    "jmp .Lmmx_seed",
    ".Lmmx_worker_b:",
    "movabs rbx, 0xB26B000000002000",
    ".Lmmx_seed:",
    "movq mm0, rbx",
    "inc rbx",
    "movq mm1, rbx",
    "inc rbx",
    "movq mm2, rbx",
    "inc rbx",
    "movq mm3, rbx",
    "inc rbx",
    "movq mm4, rbx",
    "inc rbx",
    "movq mm5, rbx",
    "inc rbx",
    "movq mm6, rbx",
    "inc rbx",
    "movq mm7, rbx",
    "xor r15d, r15d",
    ".Lmmx_round:",
    // Keep the MMX image live through multiple timer ticks without calling
    // any helper or relying on elapsed time as a correctness oracle.
    "rdtsc",
    "shl rdx, 32",
    "or rax, rdx",
    "mov r10, rax",
    "add r10, 30000000",
    ".Lmmx_spin:",
    "pause",
    "rdtsc",
    "shl rdx, 32",
    "or rax, rdx",
    "cmp rax, r10",
    "jb .Lmmx_spin",
    "mov eax, 62",
    "xor edi, edi",
    "xor esi, esi",
    "xor edx, edx",
    "xor r10d, r10d",
    "xor r8d, r8d",
    "xor r9d, r9d",
    "syscall",
    "test rax, rax",
    "jnz .Lmmx_yield_fail",
    "cmp r14d, 1",
    "jne .Lmmx_expect_b",
    "movabs r12, 0xA15A000000001000",
    "jmp .Lmmx_verify",
    ".Lmmx_expect_b:",
    "movabs r12, 0xB26B000000002000",
    ".Lmmx_verify:",
    "movq rax, mm0",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm1",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm2",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm3",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm4",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm5",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm6",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r12",
    "movq rax, mm7",
    "cmp rax, r12",
    "jne .Lmmx_state_fail",
    "inc r15d",
    "cmp r15d, 4",
    "jb .Lmmx_round",
    "emms",
    "mov edi, 42",
    "jmp .Lmmx_exit",
    ".Lmmx_yield_fail:",
    "emms",
    "mov edi, 91",
    "jmp .Lmmx_exit",
    ".Lmmx_state_fail:",
    "emms",
    "mov edi, 92",
    ".Lmmx_exit:",
    "mov eax, 2",
    "syscall",
    "ud2",
);

#[panic_handler]
fn panic(_: &PanicInfo) -> ! {
    loop {
        core::hint::spin_loop();
    }
}
