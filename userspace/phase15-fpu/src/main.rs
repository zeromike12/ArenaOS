#![no_std]
#![no_main]

use core::arch::global_asm;
use core::panic::PanicInfo;

// The fixture is deliberately handwritten: it inspects the architectural
// register image directly and never relies on Rust or C floating-point ABI
// assumptions. Arguments are the kernel's native first argument in RDI:
//   1 / 2                 normal distinct SIMD worker
//   bit63 | thread_id     SYS_THREAD_JOIN blocker/resumer
//   bit62 | 1 / 2 / 3     #XF / #MF / unsupported AVX #UD negative control
global_asm!(
    ".section .text",
    ".p2align 4",
    ".globl _start",
    "_start:",
    // User RSP begins 8 mod 16. Reserve 632 bytes to align the FXSAVE area;
    // the final 64 bytes hold test scratch and the blocked-join status word.
    "sub rsp, 0x278",
    "mov r15d, 0",
    "mov r13d, 0",
    "mov r14d, 0xA000",
    "bt rdi, 63",
    "jc .Lphase15_join_arg",
    "bt rdi, 62",
    "jc .Lphase15_fault_arg",
    "cmp edi, 1",
    "je .Lphase15_worker_a",
    "cmp edi, 2",
    "je .Lphase15_worker_b",
    "mov edi, 80",
    "jmp .Lphase15_exit",
    ".Lphase15_worker_a:",
    "mov r14d, 0xA000",
    "jmp .Lphase15_check_clean",
    ".Lphase15_worker_b:",
    "mov r14d, 0xB000",
    "jmp .Lphase15_check_clean",
    ".Lphase15_join_arg:",
    "mov r12, rdi",
    "btr r12, 63",
    "mov r13d, 1",
    "mov r14d, 0xC000",
    "jmp .Lphase15_check_clean",
    ".Lphase15_fault_arg:",
    "mov r15d, edi",
    "and r15d, 0xFF",
    "add r15d, 0x100",
    "mov r14d, 0xC000",
    ".Lphase15_check_clean:",
    // A first-entry FXSAVE checks actual ring-3 state. FXSAVE64 uses the
    // architectural 64-bit layout: MXCSR at 24, ST/MM at 32..160, XMM at
    // 160..416. The MXCSR mask's documented zero fallback is applied here.
    "fxsave64 [rsp]",
    "cmp word ptr [rsp], 0x037F",
    "jne .Lphase15_clean_fail",
    "cmp word ptr [rsp + 2], 0",
    "jne .Lphase15_clean_fail",
    "cmp byte ptr [rsp + 4], 0",
    "jne .Lphase15_clean_fail",
    "mov eax, dword ptr [rsp + 28]",
    "test eax, eax",
    "jnz .Lphase15_have_mask",
    "mov eax, 0xFFBF",
    ".Lphase15_have_mask:",
    "and eax, 0x1F80",
    "cmp dword ptr [rsp + 24], eax",
    "jne .Lphase15_clean_fail",
    "mov ecx, 8",
    "lea rsi, [rsp + 32]",
    ".Lphase15_clean_x87:",
    "cmp qword ptr [rsi], 0",
    "jne .Lphase15_clean_fail",
    "cmp qword ptr [rsi + 8], 0",
    "jne .Lphase15_clean_fail",
    "add rsi, 16",
    "loop .Lphase15_clean_x87",
    "mov ecx, 16",
    "lea rsi, [rsp + 160]",
    ".Lphase15_clean_xmm:",
    "cmp qword ptr [rsi], 0",
    "jne .Lphase15_clean_fail",
    "cmp qword ptr [rsi + 8], 0",
    "jne .Lphase15_clean_fail",
    "add rsi, 16",
    "loop .Lphase15_clean_xmm",
    "cmp r15d, 0x101",
    "je .Lphase15_fault_xf",
    "cmp r15d, 0x102",
    "je .Lphase15_fault_mf",
    "cmp r15d, 0x103",
    "je .Lphase15_fault_ud",
    "",
    // x87 arithmetic: 1.5 + 2.25 = 3.75, checked by its binary64 bits.
    "fld qword ptr [rip + .Lphase15_f64_1_5]",
    "fadd qword ptr [rip + .Lphase15_f64_2_25]",
    "fstp qword ptr [rsp + 0x200]",
    "mov rax, qword ptr [rsp + 0x200]",
    "movabs rbx, 0x400E000000000000",
    "cmp rax, rbx",
    "jne .Lphase15_x87_arith_fail",
    // SSE scalar addition and ordered comparison use exact binary fractions.
    "movss xmm0, dword ptr [rip + .Lphase15_f32_1_5]",
    "addss xmm0, dword ptr [rip + .Lphase15_f32_2_25]",
    "ucomiss xmm0, dword ptr [rip + .Lphase15_f32_3_75]",
    "jp .Lphase15_sse_arith_fail",
    "jne .Lphase15_sse_arith_fail",
    "movd eax, xmm0",
    "cmp eax, 0x40700000",
    "jne .Lphase15_sse_arith_fail",
    // MXCSR-directed scalar conversion: round down 1.5→1, round up 1.5→2.
    "mov dword ptr [rsp + 0x208], 0x00003F80",
    "ldmxcsr dword ptr [rsp + 0x208]",
    "movss xmm0, dword ptr [rip + .Lphase15_f32_1_5]",
    "cvtss2si eax, xmm0",
    "cmp eax, 1",
    "jne .Lphase15_round_fail",
    "mov dword ptr [rsp + 0x208], 0x00005F80",
    "ldmxcsr dword ptr [rsp + 0x208]",
    "movss xmm0, dword ptr [rip + .Lphase15_f32_1_5]",
    "cvtss2si eax, xmm0",
    "cmp eax, 2",
    "jne .Lphase15_round_fail",
    // x87 control-word-directed FISTP conversion, also compared as integers.
    "fldcw word ptr [rip + .Lphase15_cw_down]",
    "fld qword ptr [rip + .Lphase15_f64_1_5]",
    "fistp qword ptr [rsp + 0x200]",
    "cmp qword ptr [rsp + 0x200], 1",
    "jne .Lphase15_round_fail",
    "fldcw word ptr [rip + .Lphase15_cw_up]",
    "fld qword ptr [rip + .Lphase15_f64_1_5]",
    "fistp qword ptr [rsp + 0x200]",
    "cmp qword ptr [rsp + 0x200], 2",
    "jne .Lphase15_round_fail",
    "fnclex",
    // Set task-specific x87 RC and MXCSR RC before filling x87/XMM state.
    "cmp r14d, 0xA000",
    "je .Lphase15_state_a",
    "cmp r14d, 0xB000",
    "je .Lphase15_state_b",
    "mov word ptr [rsp + 0x234], 0x0F7F",
    "mov dword ptr [rsp + 0x230], 0x00007F80",
    "jmp .Lphase15_state_ready",
    ".Lphase15_state_a:",
    "mov word ptr [rsp + 0x234], 0x077F",
    "mov dword ptr [rsp + 0x230], 0x00003F80",
    "jmp .Lphase15_state_ready",
    ".Lphase15_state_b:",
    "mov word ptr [rsp + 0x234], 0x0B7F",
    "mov dword ptr [rsp + 0x230], 0x00005F80",
    ".Lphase15_state_ready:",
    "fldcw word ptr [rsp + 0x234]",
    "ldmxcsr dword ptr [rsp + 0x230]",
    // A masked inexact scalar conversion sets MXCSR.PE (status bit 5). Keep
    // that sticky status bit in the expected image across scheduler switches.
    "movss xmm1, dword ptr [rip + .Lphase15_f32_1_5]",
    "cvtss2si eax, xmm1",
    "or dword ptr [rsp + 0x230], 0x20",
    // Leave three distinct x87 values live across every switch: ST0=3.75,
    // ST1=2.0, ST2=1.0. The reviewed verifier pops and reconstructs them.
    "fld1",
    "fld qword ptr [rip + .Lphase15_f64_2]",
    "fld qword ptr [rip + .Lphase15_f64_1_5]",
    "fadd qword ptr [rip + .Lphase15_f64_2_25]",
    // XMM0-XMM15 each get a task- and register-specific 128-bit pattern.
    "mov eax, r14d",
    "movd xmm0, eax",
    "pshufd xmm0, xmm0, 0",
    "mov eax, r14d",
    "add eax, 1",
    "movd xmm1, eax",
    "pshufd xmm1, xmm1, 0",
    "mov eax, r14d",
    "add eax, 2",
    "movd xmm2, eax",
    "pshufd xmm2, xmm2, 0",
    "mov eax, r14d",
    "add eax, 3",
    "movd xmm3, eax",
    "pshufd xmm3, xmm3, 0",
    "mov eax, r14d",
    "add eax, 4",
    "movd xmm4, eax",
    "pshufd xmm4, xmm4, 0",
    "mov eax, r14d",
    "add eax, 5",
    "movd xmm5, eax",
    "pshufd xmm5, xmm5, 0",
    "mov eax, r14d",
    "add eax, 6",
    "movd xmm6, eax",
    "pshufd xmm6, xmm6, 0",
    "mov eax, r14d",
    "add eax, 7",
    "movd xmm7, eax",
    "pshufd xmm7, xmm7, 0",
    "mov eax, r14d",
    "add eax, 8",
    "movd xmm8, eax",
    "pshufd xmm8, xmm8, 0",
    "mov eax, r14d",
    "add eax, 9",
    "movd xmm9, eax",
    "pshufd xmm9, xmm9, 0",
    "mov eax, r14d",
    "add eax, 10",
    "movd xmm10, eax",
    "pshufd xmm10, xmm10, 0",
    "mov eax, r14d",
    "add eax, 11",
    "movd xmm11, eax",
    "pshufd xmm11, xmm11, 0",
    "mov eax, r14d",
    "add eax, 12",
    "movd xmm12, eax",
    "pshufd xmm12, xmm12, 0",
    "mov eax, r14d",
    "add eax, 13",
    "movd xmm13, eax",
    "pshufd xmm13, xmm13, 0",
    "mov eax, r14d",
    "add eax, 14",
    "movd xmm14, eax",
    "pshufd xmm14, xmm14, 0",
    "mov eax, r14d",
    "add eax, 15",
    "movd xmm15, eax",
    "pshufd xmm15, xmm15, 0",
    "paddd xmm0, xmmword ptr [rip + .Lphase15_increment]",
    // The joiner parks in SYS_THREAD_JOIN with its FPU state live. Worker B
    // exits with 42; join must wake this thread and return without state loss.
    "cmp r13d, 1",
    "jne .Lphase15_start_rounds",
    "mov eax, 65",
    "mov rdi, r12",
    "lea rsi, [rsp + 0x238]",
    "xor edx, edx",
    "xor r10d, r10d",
    "xor r8d, r8d",
    "xor r9d, r9d",
    "syscall",
    "test rax, rax",
    "jnz .Lphase15_join_fail",
    "cmp qword ptr [rsp + 0x238], 42",
    "jne .Lphase15_join_fail",
    "call .Lphase15_verify_state",
    "test eax, eax",
    "jz .Lphase15_join_checked",
    "mov edi, eax",
    "jmp .Lphase15_exit",
    ".Lphase15_join_checked:",
    ".Lphase15_start_rounds:",
    "xor r15d, r15d",
    ".Lphase15_round:",
    // Hold x87, MXCSR, and all XMM registers live while real timer ticks
    // preempt the user thread. TSC is only a loop bound, not the test oracle.
    "rdtsc",
    "shl rdx, 32",
    "or rax, rdx",
    "mov r10, rax",
    "add r10, 50000000",
    ".Lphase15_spin:",
    "pause",
    "rdtsc",
    "shl rdx, 32",
    "or rax, rdx",
    "cmp rax, r10",
    "jb .Lphase15_spin",
    // SYS_THREAD_YIELD tests syscall entry/return and cooperative switching.
    "mov eax, 62",
    "xor edi, edi",
    "xor esi, esi",
    "xor edx, edx",
    "xor r10d, r10d",
    "xor r8d, r8d",
    "xor r9d, r9d",
    "syscall",
    "test rax, rax",
    "jnz .Lphase15_syscall_fail",
    "call .Lphase15_verify_state",
    "test eax, eax",
    "jz .Lphase15_round_checked",
    "mov edi, eax",
    "jmp .Lphase15_exit",
    ".Lphase15_round_checked:",
    "inc r15d",
    "cmp r15d, 4",
    "jb .Lphase15_round",
    "mov edi, 42",
    "jmp .Lphase15_exit",
    // Expected CPL3 negative controls: unmasked SSE invalid operation -> #XF;
    // unmasked x87 divide-by-zero + FWAIT -> #MF; VZEROUPPER -> #UD because
    // CR4.OSXSAVE is deliberately clear. Reaching the fallback is a failure.
    ".Lphase15_fault_xf:",
    "mov dword ptr [rsp + 0x230], 0x00001F00",
    "ldmxcsr dword ptr [rsp + 0x230]",
    "mov eax, 0xBF800000",
    "movd xmm0, eax",
    "sqrtss xmm0, xmm0",
    // Reaching this instruction means QEMU did not deliver the requested
    // #XF; return the observed MXCSR as a diagnostic status for the harness.
    "stmxcsr dword ptr [rsp + 0x230]",
    "mov edi, dword ptr [rsp + 0x230]",
    "jmp .Lphase15_exit",
    ".Lphase15_fault_mf:",
    "mov word ptr [rsp + 0x234], 0x037B",
    "fldcw word ptr [rsp + 0x234]",
    "fld1",
    "fldz",
    "fdivp st(1), st(0)",
    "fwait",
    "mov edi, 92",
    "jmp .Lphase15_exit",
    ".Lphase15_fault_ud:",
    // The OSXSAVE contract must be visible at CPL3 too. On an AVX-capable
    // host, VZEROUPPER must #UD because the kernel leaves OSXSAVE clear; on
    // an older host, UD2 still verifies the contained #UD path.
    "mov eax, 1",
    "cpuid",
    "test ecx, 0x08000000",
    "jnz .Lphase15_osxsave_leaked",
    "test ecx, 0x10000000",
    "jz .Lphase15_ud2_fallback",
    "vzeroupper",
    "mov edi, 93",
    "jmp .Lphase15_exit",
    ".Lphase15_ud2_fallback:",
    "ud2",
    ".Lphase15_osxsave_leaked:",
    "mov edi, 94",
    "jmp .Lphase15_exit",
    ".Lphase15_clean_fail:",
    "mov edi, 81",
    "jmp .Lphase15_exit",
    ".Lphase15_x87_arith_fail:",
    "mov edi, 82",
    "jmp .Lphase15_exit",
    ".Lphase15_sse_arith_fail:",
    "mov edi, 83",
    "jmp .Lphase15_exit",
    ".Lphase15_round_fail:",
    "mov edi, 84",
    "jmp .Lphase15_exit",
    ".Lphase15_join_fail:",
    "mov edi, 90",
    "jmp .Lphase15_exit",
    ".Lphase15_syscall_fail:",
    "mov edi, 89",
    ".Lphase15_exit:",
    "mov eax, 2",
    "syscall",
    "ud2",
    // Called with the user stack base 16-byte aligned. The return-address
    // push makes RSP 8 mod 16, so the FXSAVE target [rsp+8] stays aligned.
    ".Lphase15_verify_state:",
    "fxsave64 [rsp + 8]",
    "mov ax, word ptr [rsp + 8]",
    "cmp ax, word ptr [rsp + 572]",
    "jne .Lphase15_verify_control_fail",
    "cmp word ptr [rsp + 10], 0x2800",
    "jne .Lphase15_verify_x87_fail",
    "cmp byte ptr [rsp + 12], 0xE0",
    "jne .Lphase15_verify_x87_fail",
    // MXCSR (offset 24 in the FXSAVE image) retains its distinct per-thread
    // rounding control and the sticky inexact status set by a real conversion.
    "mov eax, dword ptr [rsp + 568]",
    "cmp dword ptr [rsp + 32], eax",
    "jne .Lphase15_verify_control_fail",
    // Store and compare the actual x87 stack values in 80-bit format, then
    // reconstruct the exact same stack for the next scheduler transition.
    "fstp tbyte ptr [rsp + 520]",
    "mov rax, qword ptr [rsp + 520]",
    "movabs rdx, 0xF000000000000000",
    "cmp rax, rdx",
    "jne .Lphase15_verify_x87_fail",
    "cmp word ptr [rsp + 528], 0x4000",
    "jne .Lphase15_verify_x87_fail",
    "fstp tbyte ptr [rsp + 536]",
    "mov rax, qword ptr [rsp + 536]",
    "movabs rdx, 0x8000000000000000",
    "cmp rax, rdx",
    "jne .Lphase15_verify_x87_fail",
    "cmp word ptr [rsp + 544], 0x4000",
    "jne .Lphase15_verify_x87_fail",
    "fstp tbyte ptr [rsp + 552]",
    "mov rax, qword ptr [rsp + 552]",
    "cmp rax, rdx",
    "jne .Lphase15_verify_x87_fail",
    "cmp word ptr [rsp + 560], 0x3FFF",
    "jne .Lphase15_verify_x87_fail",
    // FXSAVE image base is RSP+8; compare every dword of XMM0-XMM15.
    "lea rsi, [rsp + 168]",
    "xor ecx, ecx",
    ".Lphase15_verify_xmm_loop:",
    "mov eax, r14d",
    "test ecx, ecx",
    "jnz .Lphase15_verify_xmm_index",
    "add eax, 7",
    "jmp .Lphase15_verify_xmm_compare",
    ".Lphase15_verify_xmm_index:",
    "add eax, ecx",
    ".Lphase15_verify_xmm_compare:",
    "cmp dword ptr [rsi], eax",
    "jne .Lphase15_verify_xmm_fail",
    "cmp dword ptr [rsi + 4], eax",
    "jne .Lphase15_verify_xmm_fail",
    "cmp dword ptr [rsi + 8], eax",
    "jne .Lphase15_verify_xmm_fail",
    "cmp dword ptr [rsi + 12], eax",
    "jne .Lphase15_verify_xmm_fail",
    "add rsi, 16",
    "inc ecx",
    "cmp ecx, 16",
    "jb .Lphase15_verify_xmm_loop",
    // Recreate ST0=3.75, ST1=2, ST2=1 without changing CW/MXCSR.
    "fld1",
    "fld qword ptr [rip + .Lphase15_f64_2]",
    "fld qword ptr [rip + .Lphase15_f64_1_5]",
    "fadd qword ptr [rip + .Lphase15_f64_2_25]",
    "xor eax, eax",
    "ret",
    ".Lphase15_verify_control_fail:",
    "mov eax, 86",
    "ret",
    ".Lphase15_verify_x87_fail:",
    "mov eax, 87",
    "ret",
    ".Lphase15_verify_xmm_fail:",
    "mov eax, 88",
    "ret",
    ".section .rodata",
    ".p2align 4",
    ".Lphase15_increment:",
    ".long 7, 7, 7, 7",
    ".Lphase15_f32_1:",
    ".long 0x3F800000",
    ".Lphase15_f32_1_5:",
    ".long 0x3FC00000",
    ".Lphase15_f32_2_25:",
    ".long 0x40100000",
    ".Lphase15_f32_3_75:",
    ".long 0x40700000",
    ".Lphase15_f64_1_5:",
    ".quad 0x3FF8000000000000",
    ".Lphase15_f64_2_25:",
    ".quad 0x4002000000000000",
    ".Lphase15_f64_2:",
    ".quad 0x4000000000000000",
    ".Lphase15_cw_down:",
    ".short 0x077F",
    ".Lphase15_cw_up:",
    ".short 0x0B7F",
    ".section .phase15_data,\"aw\",@progbits",
    ".quad 0x5048415345313546",
);

#[panic_handler]
fn panic(_: &PanicInfo<'_>) -> ! {
    loop {
        core::hint::spin_loop();
    }
}
